"""Embeds chrome://spaces page files as C++ string constants.

The page is three small files, so a generated header avoids adding a grit
resource bundle (and a patch to register it) for Bark's own WebUI.
"""
import argparse
from pathlib import Path

DELIMITER = 'BARK_RESOURCE'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', required=True)
    parser.add_argument('resources', nargs='+', help='NAME=PATH pairs')
    args = parser.parse_args()
    lines = ['// Generated by embed_resources.py. Do not edit.',
             '#ifndef BARK_SPACES_UI_SPACES_RESOURCES_H_',
             '#define BARK_SPACES_UI_SPACES_RESOURCES_H_',
             'namespace bark {']
    for pair in args.resources:
        name, path = pair.split('=', 1)
        text = Path(path).read_text(encoding='utf-8')
        if ')' + DELIMITER + '"' in text:
            raise SystemExit(path + ' contains the raw string delimiter')
        lines.append(f'inline constexpr char {name}[] = R"{DELIMITER}({text}){DELIMITER}";')
    lines += ['}  // namespace bark', '#endif', '']
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
